/// Rewrite baked brand outputs under [root].
///
/// `tool/brand.sh pistisai` restores the upstream product. Another id writes
/// that brand. HTML legal pages are rendered from `tool/brand/templates`.
void writeBrand(String root, BrandConfig brand) {
  _write('$root/lib/brand/active_brand.g.dart', renderActiveBrandDart(brand));
  _write('$root/linux/runner/brand_config.h', renderLinuxHeader(brand));
  _write('$root/windows/runner/brand_config.h', renderWindowsHeader(brand));
  _write('$root/macos/Runner/Configs/Brand.xcconfig', renderMacXcconfig(brand));
  _write(
    '$root/android/app/src/main/res/values/brand_strings.xml',
    renderAndroidStrings(brand),
  );
  _patch('$root/web/index.html', (source) => applyWebIndex(source, brand));
  _patch('$root/web/manifest.json', (source) => applyManifest(source, brand));
  _patch(
    '$root/web/privacy.html',
    (_) =>
        renderTemplate(_read('$root/tool/brand/templates/privacy.html'), brand),
  );
  _patch(
    '$root/web/terms.html',
    (_) =>
        renderTemplate(_read('$root/tool/brand/templates/terms.html'), brand),
  );
  _patch(
    '$root/web/install.sh',
    (_) =>
        renderTemplate(_read('$root/tool/brand/templates/install.sh'), brand),
  );
  _patch(
    '$root/web/install.ps1',
    (_) =>
        renderTemplate(_read('$root/tool/brand/templates/install.ps1'), brand),
  );
  _patch(
    '$root/linux/app.pistisai.desktop',
    (source) => applyDesktopName(source, brand),
  );
  _patch(
    '$root/assets/linux/pistisai.desktop',
    (source) => applyDesktopName(source, brand),
  );
  _patch(
    '$root/windows/installer/Pistisai.iss',
    (source) => applyInstaller(source, brand),
  );
  _patch(
    '$root/linux/com.Pistisai.Pistisai.metainfo.xml',
    (source) => applyMetainfo(source, brand),
  );
  _patch(
    '$root/windows/runner/Runner.rc',
    (source) => applyWindowsRc(source, brand),
  );
}

