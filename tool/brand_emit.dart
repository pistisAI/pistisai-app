String renderLinuxHeader(BrandConfig brand) {
  return '''
#ifndef BRAND_CONFIG_H_
#define BRAND_CONFIG_H_

/* Window title only. APPLICATION_ID and the binary name stay in CMake. */
#define BRAND_WINDOW_TITLE "${_cString(brand.windowTitle)}"

#endif
''';
}

String renderWindowsHeader(BrandConfig brand) {
  return '''
#ifndef BRAND_CONFIG_H_
#define BRAND_CONFIG_H_

#define BRAND_WINDOW_TITLE L"${_cString(brand.windowTitle)}"
#define BRAND_COMPANY_NAME "${_cString(brand.companyName)}"
#define BRAND_PRODUCT_NAME "${_cString(brand.productName)}"
#define BRAND_FILE_DESCRIPTION "${_cString(brand.fileDescription)}"
