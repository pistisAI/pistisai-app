}

String renderTemplate(String template, BrandConfig brand) {
  final tokens = <String, String>{
    'product_name': brand.productName,
    'company_name': brand.companyName,
    'website_url': brand.websiteUrl,
    'website_domain': brand.websiteDomain,
    'privacy_email': brand.privacyEmail,
    'support_email': brand.supportEmail,
    'repository_url': brand.repositoryUrl,
    'repository_label': brand.repositoryLabel,
    'repository_link': _repositoryLink(brand),
    'support_url': brand.supportUrl,
    'releases_url': brand.releasesUrl,
    'github_repo': brand.githubRepoSlug,
    'artifact_prefix': brand.artifactPrefix,
    'background': brand.backgroundHex,
  };
  var rendered = template;
  for (final entry in tokens.entries) {
    rendered = rendered.replaceAll('{{${entry.key}}}', entry.value);
  }
  return rendered;
}

String applyWebIndex(String source, BrandConfig brand) {
  var out = source;
  out = _replaceAttr(out, 'name="description" content', brand.webDescription);
  out = _replaceAttr(out, 'property="og:title" content',
      '${brand.productName} — ${brand.tagline}');
  out = _replaceAttr(
      out, 'property="og:description" content', brand.socialDescription);
  out = _replaceAttr(out, 'property="og:url" content', brand.websiteUrl);
  out = _replaceAttr(
    out,
    'property="og:image" content',
    '${brand.websiteUrl}/icons/Icon-512.png',
  );
  out = _replaceAttr(out, 'name="twitter:title" content',
      '${brand.productName} — ${brand.tagline}');
  out = _replaceAttr(
      out, 'name="twitter:description" content', brand.socialDescription);
  out = _replaceAttr(
      out, 'name="apple-mobile-web-app-title" content', brand.productName);
  out = out.replaceFirst(
    RegExp(r'<title>[^<]*</title>'),
    '<title>${_html(brand.webTitle)}</title>',
  );
  out = out.replaceAll(
    RegExp(r'background-color:\s*#[0-9A-Fa-f]{6}'),
    'background-color: ${brand.backgroundHex}',
  );
  out = out.replaceFirst(
    RegExp(r'^ *https://\*\.\S+.* ws://127\.0\.0\.1:\* wss://\*\.\S+.*$',
        multiLine: true),
    '      ${cspBrandHosts(brand)}',
  );
  return out;
}

/// The brand's own origins for the web `connect-src` CSP line: every
/// subdomain of the website domain, the API host when it sits elsewhere,
/// and loopback for the local hub.
String cspBrandHosts(BrandConfig brand) {
  final domain = brand.websiteDomain;
  final api = brand.apiHost;
  final apiOutside = api != domain && !api.endsWith('.$domain');
  return [
    'https://*.$domain',
    if (apiOutside) 'https://$api',
    'http://127.0.0.1:*',
    'ws://127.0.0.1:*',
    'wss://*.$domain',
    if (apiOutside) 'wss://$api',
  ].join(' ');
}

String applyManifest(String source, BrandConfig brand) {
  var out = source;
  out = _replaceJsonString(out, 'name', brand.productName);
  out = _replaceJsonString(out, 'short_name', brand.shortName);
  out = _replaceJsonString(out, 'description', brand.manifestDescription);
  out = _replaceJsonString(out, 'background_color', brand.backgroundHex);
  out = _replaceJsonString(out, 'theme_color', brand.backgroundHex);
  return out;
}

String applyDesktopName(String source, BrandConfig brand) {
  return source.replaceFirst(
    RegExp(r'^Name=.*$', multiLine: true),
    'Name=${brand.productName}',
  );
}

String applyInstaller(String source, BrandConfig brand) {
  var out = source;
  out = out.replaceFirst(
    RegExp(r'#define MyAppName ".*"'),
    '#define MyAppName "${brand.productName}"',
  );
  out = out.replaceFirst(
    RegExp(r'#define MyAppPublisher ".*"'),
    '#define MyAppPublisher "${brand.companyName}"',
  );
  out = out.replaceFirst(
    RegExp(r'#define MyAppURL ".*"'),
    '#define MyAppURL "${brand.websiteUrl}"',
  );
  return out;
}

String applyMetainfo(String source, BrandConfig brand) {
  var out = source;
  out = out.replaceFirst(
    RegExp(r'<name>[^<]*</name>'),
    '<name>${_xml(brand.productName)}</name>',
  );
  out = out.replaceFirst(
    RegExp(r'<summary>[^<]*</summary>'),
    '<summary>${_xml(brand.appstreamSummary)}</summary>',
  );
  out = out.replaceFirst(
    RegExp(r'<developer_name>[^<]*</developer_name>'),
    '<developer_name>${_xml(brand.developerName)}</developer_name>',
  );
  out = out.replaceFirstMapped(
    RegExp(r'(<description>\s*<p>)([\s\S]*?)(</p>)'),
    (match) {
      final current = match.group(2)!.replaceAll(RegExp(r'\s+'), ' ').trim();
      final next =
          brand.appstreamDescription.replaceAll(RegExp(r'\s+'), ' ').trim();
      if (current == next) {
        return match.group(0)!;
      }
      return '${match.group(1)}\n      ${_xml(brand.appstreamDescription)}\n    ${match.group(3)}';
    },
  );
  return out;
}

String _repositoryLink(BrandConfig brand) {
  final uri = Uri.parse(brand.repositoryUrl);
  if (uri.host.isEmpty) {
    return brand.repositoryLabel;
  }
  return '${uri.host}${uri.path}';
}

/// Point version-info strings at the generated header. Safe to run twice.
String applyWindowsRc(String source, BrandConfig brand) {
  var out = source;
  if (!out.contains('#include "brand_config.h"')) {
    out = out.replaceFirst(
      '#include "resource.h"',
      '#include "resource.h"\n#include "brand_config.h"',
    );
  }
  out = out.replaceAll(
    RegExp(r'VALUE "CompanyName", "[^"]*" "\\0"'),
    'VALUE "CompanyName", BRAND_COMPANY_NAME "\\0"',
  );
  out = out.replaceAll(
    RegExp(r'VALUE "FileDescription", "[^"]*" "\\0"'),
    'VALUE "FileDescription", BRAND_FILE_DESCRIPTION "\\0"',
  );
  out = out.replaceAll(
    RegExp(r'VALUE "ProductName", "[^"]*" "\\0"'),
    'VALUE "ProductName", BRAND_PRODUCT_NAME "\\0"',
  );
  out = out.replaceAll(
    RegExp(r'VALUE "LegalCopyright", "[^"]*" "\\0"'),
    'VALUE "LegalCopyright", BRAND_LEGAL_COPYRIGHT "\\0"',
  );
  // brand is unused when the macros already point at the header. The header
  // file carries the strings. Touching [brand] keeps the signature honest
  // for callers that pass the active brand.
  if (brand.windowTitle.isEmpty) {
    throw StateError('window title is empty');
  }
  return out;
}

String _hex(int argb) =>
    '0x${argb.toRadixString(16).padLeft(8, '0').toUpperCase()}';

String _cString(String value) =>
    value.replaceAll(r'\', r'\\').replaceAll('"', r'\"');

String _xml(String value) => value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');

String _html(String value) => _xml(value);

String _replaceAttr(String source, String attrPrefix, String value) {
  final pattern = RegExp('${RegExp.escape(attrPrefix)}="[^"]*"');
  return source.replaceFirst(pattern, '$attrPrefix="${_html(value)}"');
}

String _replaceJsonString(String source, String key, String value) {
  final encoded = jsonEncode(value);
  final pattern = RegExp('"$key":\\s*"[^"]*"');
  return source.replaceFirst(pattern, '"$key": $encoded');
}

String _read(String path) => File(path).readAsStringSync();

/// Writes [contents] to [path]. Skips a platform folder that is absent, as in
/// a trimmed Docker build context that only builds web.
void _write(String path, String contents) {
  final file = File(path);
  if (!file.parent.existsSync()) {
    stdout.writeln('Skipped $path (folder not present)');
    return;
  }
  file.writeAsStringSync(contents);
}

void _patch(String path, String Function(String source) transform) {
  final file = File(path);
  if (!file.existsSync()) {
    stdout.writeln('Skipped $path (not present)');
    return;
  }
  final next = transform(file.readAsStringSync());
  if (next != file.readAsStringSync()) {
    file.writeAsStringSync(next);
  }
}
